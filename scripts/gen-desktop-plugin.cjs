// Generates the Openfield Football desktop plugin (plugin.js) by embedding the
// game's single-file HTML into the plugin source as a srcdoc string.
// Usage: node scripts/gen-desktop-plugin.cjs
// Output: <HERMES_HOME>/desktop-plugins/openfield-football/plugin.js
const fs = require('fs');
const path = require('path');

const GAME = path.resolve(__dirname, '..', 'open_field_v6.html');
const OUT = process.env.HERMES_HOME
  ? path.join(process.env.HERMES_HOME, 'desktop-plugins', 'openfield-football', 'plugin.js')
  : path.join('C:', 'Users', 'rpresendieu', 'AppData', 'Local', 'hermes', 'desktop-plugins', 'openfield-football', 'plugin.js');

const html = fs.readFileSync(GAME, 'utf8');

// JSON-encode the whole document as a JS string literal, then escape every
// `</` as `<\/` so no HTML-parser edge case can ever close the script early
// (valid in JS: `\/` === `/`).
const encoded = JSON.stringify(html).split('</').join('<\\/');

const plugin = `/**
 * Openfield Football — Hermes desktop plugin.
 * Generated by scripts/gen-desktop-plugin.cjs from open_field_v6.html.
 * Re-run that script after updating the game to refresh the embedded build.
 */
import { jsx } from 'react/jsx-runtime'
import { ROUTES_AREA, SIDEBAR_NAV_AREA, PALETTE_AREA } from '@hermes/plugin-sdk'

const ID = 'openfield-football'

// Embedded single-file game (canvas + inline JS). Kept as srcdoc so the game
// runs fully inside the app: no file:// access, no CORS, no server needed.
const GAME_HTML = ${encoded}

function focusIframe(e) {
  try { e.target.contentWindow && e.target.contentWindow.focus() } catch (_) {}
}

function GamePage() {
  return jsx('div', {
    className: 'h-full w-full overflow-hidden bg-[var(--ui-editor-bg)]',
    children: jsx('iframe', {
      title: 'Openfield Football',
      srcDoc: GAME_HTML,
      className: 'h-full w-full border-0',
      allow: 'autoplay; fullscreen',
      onLoad: focusIframe,
      onClick: focusIframe
    })
  })
}

export default {
  id: ID,
  name: 'Openfield Football',
  register(ctx) {
    // Full-page route: the game mounts in the workspace pane like a built-in view.
    ctx.register({
      id: 'game',
      area: ROUTES_AREA,
      data: { path: '/openfield-football' },
      render: () => jsx(GamePage, {})
    })
    // Sidebar nav row so it is one click away.
    ctx.register({
      id: 'nav',
      area: SIDEBAR_NAV_AREA,
      data: { path: '/openfield-football', label: 'Openfield Football', codicon: 'symbol-event' }
    })
    // Command-palette entry (Ctrl+K → "Openfield Football").
    ctx.register({
      id: 'palette',
      area: PALETTE_AREA,
      data: {
        id: 'openfield-football.open',
        label: 'Open Openfield Football',
        keywords: ['football', 'game', 'openfield'],
        run: () => host.navigate('/openfield-football')
      }
    })
  }
}
`

// host is used via the palette run closure — import it explicitly.
const final = plugin.replace(
  "import { ROUTES_AREA, SIDEBAR_NAV_AREA, PALETTE_AREA } from '@hermes/plugin-sdk'",
  "import { host, ROUTES_AREA, SIDEBAR_NAV_AREA, PALETTE_AREA } from '@hermes/plugin-sdk'"
)

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, final, 'utf8');
console.log('Wrote', OUT, '(' + Buffer.byteLength(final, 'utf8') + ' bytes)');
